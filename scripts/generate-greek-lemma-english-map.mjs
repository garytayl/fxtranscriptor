#!/usr/bin/env node
/**
 * Builds lib/bible/greek-lemma-english-gloss.generated.ts from OpenScriptures
 * Strong's Greek dictionary (same source as lib/bible/lexicon-openscriptures.ts).
 * Run: node scripts/generate-greek-lemma-english-map.mjs
 */
import fs from "node:fs"
import https from "node:https"
import { fileURLToPath } from "node:url"

const OUT_PATH = fileURLToPath(
  new URL("../lib/bible/greek-lemma-english-gloss.generated.ts", import.meta.url),
)
const STRONGS_GREEK_DICT_URL =
  "https://cdn.jsdelivr.net/gh/openscriptures/strongs@master/greek/strongs-greek-dictionary.js"

function fetchText(url) {
  return new Promise((resolve, reject) => {
    https
      .get(url, (r) => {
        let d = ""
        r.on("data", (c) => (d += c))
        r.on("end", () => resolve(d))
      })
      .on("error", reject)
  })
}

/** Short English label for multiple-choice (KJV def is often comma-heavy). */
function quizLabelFromKjvDef(kjv) {
  if (!kjv || typeof kjv !== "string") return ""
  const first = kjv.split(";")[0].split(",")[0].trim().replace(/^X\s+/i, "").trim()
  if (!first) return ""
  const words = first.split(/\s+/).filter(Boolean)
  let s = words.slice(0, 3).join(" ")
  if (s.length > 48) s = `${s.slice(0, 45).trim()}…`
  return s
}

async function main() {
  const text = await fetchText(STRONGS_GREEK_DICT_URL)
  const start = text.indexOf("{")
  const end = text.lastIndexOf("}")
  const obj = JSON.parse(text.slice(start, end + 1))
  /** @type {Map<string, string>} */
  const lemmaToLabel = new Map()
  /** First Strong's code per Greek lemma (dictionary keys are G###). */
  /** @type {Map<string, string>} */
  const lemmaToStrongs = new Map()
  for (const [codeRaw, raw] of Object.entries(obj)) {
    const lemma = (raw.lemma ?? "").trim()
    if (!lemma) continue
    const code = String(codeRaw).toUpperCase()
    if (!lemmaToStrongs.has(lemma)) lemmaToStrongs.set(lemma, code)
  }
  for (const raw of Object.values(obj)) {
    const lemma = (raw.lemma ?? "").trim()
    const kjv = raw.kjv_def ?? ""
    if (!lemma) continue
    const label = quizLabelFromKjvDef(kjv)
    if (!label) continue
    if (!lemmaToLabel.has(lemma)) lemmaToLabel.set(lemma, label)
  }
  const entries = [...lemmaToLabel.entries()].sort((a, b) => a[0].localeCompare(b[0], "el"))
  const lines = entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  const strongsEntries = [...lemmaToStrongs.entries()].sort((a, b) => a[0].localeCompare(b[0], "el"))
  const strongsLines = strongsEntries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  const out = `/* eslint-disable */
/**
 * Auto-generated by scripts/generate-greek-lemma-english-map.mjs
 * Greek lemma → short English gloss (from Strong's KJV definitions, OpenScriptures).
 * Do not edit by hand; regenerate the map after dictionary updates.
 */
export const GREEK_LEMMA_ENGLISH_QUIZ: Record<string, string> = {
${lines.join("\n")}
}

/**
 * Greek lemma → Strong's Greek code (first lexicon entry per lemma in OpenScriptures key order).
 * Used to show a single Strong's lookup for a MorphGNT token (lemma-based, not verse-aligned KJV).
 */
export const GREEK_LEMMA_STRONGS_CODE: Record<string, string> = {
${strongsLines.join("\n")}
}
`
  fs.writeFileSync(OUT_PATH, out, "utf8")
  console.log(`Wrote ${lemmaToLabel.size} lemmas to ${OUT_PATH}`)
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
